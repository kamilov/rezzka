// Recreate the bundled sample with: node scripts/generate-demo.mjs
// Requires ffmpeg (with libx264) on PATH. Every frame is created by lavfi color,
// drawgrid and drawbox filters below; no images, fonts, footage or audio inputs
// are used. The twelve segments show elapsed seconds on a quiet dark grid.
import {randomUUID} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {mkdir, rename, rm} from 'node:fs/promises';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));

export async function generateDemo(outputPath = resolve(projectRoot, 'public/demo/sample.mp4')) {
  const destination = resolve(outputPath);
  const temporary = `${destination}.${randomUUID()}.tmp.mp4`;
  const filters = [
    'drawgrid=w=80:h=80:t=1:c=0x313743@0.4',
    'drawbox=x=112:y=272:w=1056:h=176:color=0x111318:t=fill',
  ];
  for (let index = 0; index < 12; index += 1) {
    const box = `x=${142 + index * 84}:y=316:w=72:h=88`;
    filters.push(`drawbox=${box}:color=0x313743:t=2`);
    filters.push(`drawbox=${box}:color=0xe6c27f@0.85:t=fill:enable='gte(t,${index})'`);
  }
  filters.push('fade=t=in:st=0:d=0.4', 'fade=t=out:st=11.6:d=0.4');
  await mkdir(dirname(destination), {recursive: true});
  try {
    const result = spawnSync('ffmpeg', [
      '-hide_banner', '-loglevel', 'error', '-nostdin', '-y',
      '-f', 'lavfi', '-i', 'color=c=0x111318:s=1280x720:r=25:d=12',
      '-vf', filters.join(','), '-an', '-t', '12',
      '-c:v', 'libx264', '-preset', 'medium', '-crf', '20',
      '-pix_fmt', 'yuv420p', '-profile:v', 'high', '-level:v', '3.1',
      '-threads', '1', '-movflags', '+faststart', '-map_metadata', '-1',
      '-metadata', 'title=Rezzka synthetic playback sample',
      '-metadata', 'comment=Generated by scripts/generate-demo.mjs from lavfi primitives; no external media inputs. GPL-3.0-only.',
      temporary,
    ], {stdio: 'inherit'});
    if (result.error) throw new Error('Cannot run ffmpeg. Install ffmpeg with libx264 and put it on PATH.', {cause: result.error});
    if (result.status !== 0) throw new Error(`ffmpeg failed (${result.status ?? result.signal}). Existing demo was preserved.`);
    await rename(temporary, destination);
  } finally {
    await rm(temporary, {force: true});
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateDemo(process.argv[2]);
}
